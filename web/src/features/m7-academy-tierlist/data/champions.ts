export function championById(id: string): Champion | undefined {
  const alvo = id.toLowerCase();
  return CHAMPIONS.find((c) => c.id.toLowerCase() === alvo);
}

export function bestLane(champion: Champion): 'TOP' | 'JG' | 'MID' | 'ADC' | 'SUP' {
  const entries = [
    ['TOP', champion.lanes.top],
    ['JG', champion.lanes.jungle],
    ['MID', champion.lanes.mid],
    ['ADC', champion.lanes.adc],
    ['SUP', champion.lanes.support],
  ] as const;
  return entries.reduce((best, atual) => (atual[1] > best[1] ? atual : best), entries[0])[0];
}
